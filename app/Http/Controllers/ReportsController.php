<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;

class ReportsController extends Controller
{
    public function diagnosisReports(Request $request)
    {
        if (! $request->isMethod('POST')) {
            return view('reports.diagnoses');
        }

        $form = $request->validate([
            'search' => 'required|string',
            'from' => 'required|date',
            'to' => 'nullable|date',
            'interval' => 'required|in:1 day,1 week,1 month',
        ]);

        extract($form);
        $to ??= date('Y-m-d');

        $intervalFormat = match ($interval) {
            '1 month' => 'yyyy-mm',
            default => 'yyyy-mm-dd',
        };

        /* select generate_series('2026-01-01'::timestamp, '2026-01-31'::timestamp, '1 day'::interval); */
        /**
         * Reports are generated by using the above sql query sample to generate a timeseries in the desired range and interval
         * https://www.postgresql.org/docs/current/functions-srf.html
         * */
        $data = DB::SELECT("select sr.month, dg.* FROM
                    (select to_char(generate_series(?::timestamp, ?::timestamp, ?::interval), '$intervalFormat') as month) sr
                    left join (
                        select count(*) as num, to_char(created_at, '$intervalFormat') as ddate
                        from documented_diagnoses dd
                        where dd.diagnoses ilike ? group by ddate order by ddate desc
                    ) dg
                    on dg.ddate = sr.month", [$from, $to, $interval, "%$search%"]);

        return view('reports.diagnoses', compact('form', 'data'));
    }
}
